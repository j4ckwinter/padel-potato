const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const read = (root, relative) => fs.readFileSync(path.join(root, relative));

function iconRecord(root, [name, designName, sourceId, sourceNodeId]) {
  const rawPath = `design-spec/assets/raw/${name}.svg`;
  const normalizedPath = `design-spec/assets/normalized/${name}.svg`;
  const raw = read(root, rawPath);
  const sourceRecord = { name, sourceNodeId };
  const xml = normalizeRawSvg(raw.toString('utf8'), sourceRecord);
  const normalized = Buffer.from(xml, 'utf8');
  const checkedInNormalized = read(root, normalizedPath);
  if (!normalized.equals(checkedInNormalized)) {
    throw new Error(`${name} normalized bytes are not the deterministic paint-only transform of raw Penpot bytes`);
  }
  const viewBox = xml.match(/viewBox="([^"]+)"/)?.[1].split(/\s+/).map(Number);
  if (!viewBox || viewBox.length !== 4) throw new Error(`${name} has no finite viewBox`);
  return { name, designName, sourceId, sourceNodeId, fileId: FILE_ID, pageId: PAGE_ID, revision: REVISION,
    rawPath, normalizedPath, rawSha256: sha256(raw), normalizedSha256: sha256(normalized), viewBox };
}

function brandRecord(root, [name, designName, sourceId, sourceNodeId, width, height]) {
  const rawPath = `design-spec/assets/raw/${name}.png`;
  const normalizedPath = `design-spec/assets/normalized/${name}.png`;
  const referencePath = `design-spec/references/components/${name}.png`;
  const raw = read(root, rawPath);
  const normalized = read(root, normalizedPath);
  return { name, designName, sourceId, sourceNodeId, fileId: FILE_ID, pageId: PAGE_ID, revision: REVISION,
    width, height, ratio: `${width / gcd(width, height)}:${height / gcd(width, height)}`, rawPath, normalizedPath,
    referencePath, rawSha256: sha256(raw), normalizedSha256: sha256(normalized), referenceSha256: sha256(read(root, referencePath)) };
}

function gcd(a, b) { return b ? gcd(b, a % b) : a; }

function registrySource(root, icons) {
  const records = icons.map((icon) => {
    const xml = read(root, icon.normalizedPath).toString('utf8').trim();
    return `  ${JSON.stringify(icon.name)}: Object.freeze(${JSON.stringify({ ...icon, xml })})`;
  });
  return `// Generated by scripts/export-penpot-assets.mjs. Do not edit.\nexport const iconRegistry = Object.freeze({\n${records.join(',\n')}\n});\n\nexport const iconNames = Object.freeze(Object.keys(iconRegistry)) as readonly (keyof typeof iconRegistry)[];\nexport type IconName = keyof typeof iconRegistry;\n`;
}

export function generateAssetOutputs({ repoRoot, write = true } = {}) {
  const root = repoRoot ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const icons = ICON_SOURCES.map((entry) => iconRecord(root, entry));
  const brands = BRAND_SOURCES.map((entry) => brandRecord(root, entry));
  const manifest = { schemaVersion: 1, generatorVersion: GENERATOR_VERSION, fileId: FILE_ID, pageId: PAGE_ID,
    pageName: '02 Components', revision: REVISION, sourceTool: 'Penpot MCP Plugin API 2.18.0', icons, brands };
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  const registryText = registrySource(root, icons);
  if (write) {
    fs.mkdirSync(path.join(root, 'src/design-system/assets/generated'), { recursive: true });
    fs.writeFileSync(path.join(root, 'design-spec/assets/penpot-assets.json'), manifestText);
    fs.writeFileSync(path.join(root, 'src/design-system/assets/generated/iconRegistry.ts'), registryText);
  }
  return { manifestText, registryText };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateAssetOutputs();
